#!/usr/bin/env node
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { createServer } from "node:http";
import { checkPublicPreviewAssets } from "../deploy/preview-assets.mjs";

const ref = "a".repeat(40), otherRef = "b".repeat(40);
const png = readFileSync(new URL("../examples/ember/assets/art/kindling.png", import.meta.url));
const font = readFileSync(new URL("../examples/secret-hitler/assets/source-fonts/GermaniaOne-Regular.ttf", import.meta.url));
const svg = Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" width="1" height="1"><rect width="1" height="1"/></svg>');
let state, requests, checks = 0;
const start = server => new Promise(resolve => server.listen(0, "127.0.0.1", () => resolve(`http://127.0.0.1:${server.address().port}`)));
const close = server => new Promise((resolve, reject) => {
  server.close(error => error ? reject(error) : resolve());
  server.closeAllConnections();
});
let externalRequests = 0;
const external = createServer((_request, response) => { externalRequests++; response.end("should never be fetched"); });
const externalOrigin = await start(external);
const server = createServer((request, response) => {
  const url = new URL(request.url, "http://fixture.test");
  requests.push({ path: url.pathname, search: url.search, headers: request.headers });
  if (url.pathname === "/api/catalog") {
    response.writeHead(state.catalogStatus || 200, { "content-type": state.catalogMime || "application/json", "set-cookie": "ignored=secret" });
    response.end(JSON.stringify(state.catalog));
  } else if (url.pathname === `/api/games/${encodeURIComponent(state.slug)}/ui`) {
    response.writeHead(state.uiStatus || 200, { "content-type": state.uiMime || "application/json", location: externalOrigin });
    response.end(JSON.stringify(state.view));
  } else {
    const rel = decodeURIComponent(url.pathname.split("/assets/")[1] || "");
    const asset = state.assets.get(rel);
    response.writeHead(asset?.status || (asset ? 200 : 404), {
      "content-type": asset?.mime || "application/json", ...asset?.headers,
    });
    response.end(asset?.bytes ?? "missing");
  }
});
const origin = await start(server);
const assetUrl = (relative, slug = "public-game", revision = ref) => `/api/games/${encodeURIComponent(slug)}/assets/${relative}?ref=${revision}&v=abc`;
const reset = (slug = "public-game") => {
  requests = [];
  state = {
    slug, catalog: { items: [{ slug, visibility: "public" }], total: 1 },
    // These are the same string-bearing shapes generated by build_hub.py:
    // printing art, symbol assets, font CSS and embedded production SVG.
    view: { slug, source_ref: ref,
      cards: [{ id: "kindling", name: "Kindling", type: "ember", text: "Gain 1 [spark]." }],
      printings: [{ id: "p_kindling_core", card_id: "kindling", set_id: "core", art: "assets/art/face.png", art_data: assetUrl("art/face.png", slug) }],
      symbols: { spark: { asset: assetUrl("icons/spark.svg", slug) } },
      fonts_css: `@font-face{font-family:Card;src:url('${assetUrl("fonts/card.ttf", slug)}')}`,
      production: { templates: [{ template_svg: `<svg><image href="${assetUrl("art/face.png", slug).replaceAll("&", "&amp;")}"/></svg>` }] },
    },
    assets: new Map([
      ["art/face.png", { mime: "image/png", bytes: png }],
      ["icons/spark.svg", { mime: "image/svg+xml; charset=utf-8", bytes: svg }],
      ["fonts/card.ttf", { mime: "font/ttf", bytes: font }],
    ]),
  };
};
const rejects = async (pattern, options) => {
  await assert.rejects(checkPublicPreviewAssets(origin, options), pattern);
  checks++;
};
try {
  reset();
  assert.deepEqual(await checkPublicPreviewAssets(origin), { slug: "public-game", ref, checked: 3, total: 3 });
  assert.equal(requests.filter(request => request.path.endsWith("face.png")).length, 1, "embedded SVG URLs deduplicate after HTML entity decoding");
  assert.ok(requests.every(request => !request.headers.authorization && !request.headers.cookie), "all preview requests stay anonymous");
  checks++;

  reset("team/game");
  assert.deepEqual(await checkPublicPreviewAssets(origin, { slug: "team/game" }), { slug: "team/game", ref, checked: 3, total: 3 });
  assert.equal(requests.some(request => request.path === "/api/catalog"), false, "explicit project selection skips the catalog");
  checks++;

  reset();
  state.catalog.items.unshift({ slug: "private-game", visibility: "private" });
  assert.equal((await checkPublicPreviewAssets(origin)).slug, "public-game", "select a public project only");
  checks++;

  for (const path of ["art/face.png", "fonts/card.ttf"]) {
    reset(); state.assets.get(path).status = 404;
    await rejects(/asset returned HTTP 404/);
  }
  reset(); state.assets.get("art/face.png").bytes = "<!DOCTYPE html><html>sign in</html>";
  await rejects(/HTML page/);
  reset(); state.assets.get("fonts/card.ttf").bytes = "<!doctype html><html>fallback</html>";
  await rejects(/HTML page/);
  reset(); state.assets.get("art/face.png").bytes = Buffer.from("not a PNG");
  await rejects(/invalid file bytes/);
  reset(); state.assets.get("fonts/card.ttf").bytes = Buffer.from("not a font");
  await rejects(/invalid file bytes/);
  reset(); state.assets.get("icons/spark.svg").bytes = Buffer.from("<html>oops</html>");
  await rejects(/HTML page/);
  reset(); state.assets.get("art/face.png").bytes = Buffer.from(`version https://git-lfs.github.com/spec/v1\noid sha256:${"c".repeat(64)}\nsize 100\n`);
  await rejects(/Git LFS pointer/);
  reset(); state.assets.get("art/face.png").bytes = Buffer.alloc(0);
  await rejects(/empty body/);
  reset(); state.assets.get("art/face.png").mime = "text/html";
  await rejects(/wrong media type/);

  reset(); state.catalog.items = [];
  await rejects(/no public project/);
  reset(); state.view = { source_ref: ref, cards: state.view.cards,
    printings: [{ ...state.view.printings[0], art: "data:image/png;base64,abc", art_data: undefined }] };
  await rejects(/no versioned assets/);
  reset(); state.view.cards = [];
  await rejects(/no card with a matching printing/);
  reset(); state.view.printings = [];
  await rejects(/no card with a matching printing/);
  reset(); state.view.printings[0].card_id = "missing-card";
  await rejects(/no card with a matching printing/);
  reset(); state.view.cards = [{}];
  await rejects(/no card with a matching printing/);
  reset(); state.view = { source_ref: ref, cards: state.view.cards,
    printings: [{ ...state.view.printings[0], art: undefined, art_data: undefined }],
    fonts_css: `url('${assetUrl("theme.css")}')` };
  state.assets.set("theme.css", { mime: "text/css", bytes: "body { color: black; }" });
  await rejects(/no versioned image assets/);
  reset(); state.view = { source_ref: ref, cards: state.view.cards,
    printings: [{ ...state.view.printings[0], art: undefined, art_data: undefined }], fonts_css: state.view.fonts_css };
  await rejects(/no versioned image assets/);
  reset(); delete state.view.printings[0].art_data;
  await rejects(/declared local card artwork is missing its exact asset URL/);
  reset(); state.view.printings[0].art = "assets/art/missing.png";
  await rejects(/declared local card artwork is missing its exact asset URL/);
  reset(); state.view.printings[0].scan = "assets/art/missing.png";
  state.view.scans = { kindling: `${externalOrigin}/remote-fallback.png` };
  await rejects(/declared local card artwork is missing its exact asset URL/);
  reset(); state.view.printings[0].scan = "assets/art/face.png";
  state.view.scans = { kindling: assetUrl("art/face.png") };
  assert.equal((await checkPublicPreviewAssets(origin)).checked, 3, "first printing's generated local scan is checked");
  checks++;
  for (const art of [`${externalOrigin}/remote.png`, `data:image/png;base64,${png.toString("base64")}`]) {
    reset(); state.view.printings[0].art = art; delete state.view.printings[0].art_data;
    assert.equal((await checkPublicPreviewAssets(origin)).checked, 3, "remote and embedded artwork declarations are not mistaken for missing local files");
    checks++;
  }
  reset(); delete state.view.source_ref;
  await rejects(/no exact source ref/);
  reset(); state.view.source_ref = "main";
  await rejects(/no exact source ref/);
  reset(); state.view.fonts_css = "url('/api/games/public-game/assets/fonts/card.ttf?v=abc')";
  await rejects(/missing its exact source ref/);
  reset(); state.view.fonts_css = `url('${assetUrl("fonts/card.ttf", "public-game", otherRef)}')`;
  await rejects(/different ref/);
  reset(); state.view.fonts_css = `url('${assetUrl("fonts/card.ttf")}&ref=${ref}')`;
  await rejects(/exact source ref/);

  reset(); state.assets.get("art/face.png").status = 302;
  state.assets.get("art/face.png").headers = { location: externalOrigin + "/secret" };
  await rejects(/HTTP 302/);
  reset(); state.uiStatus = 302;
  await rejects(/project view returned HTTP 302/);
  reset(); state.uiMime = "text/html";
  await rejects(/project view did not return JSON/);
  reset(); state.assets.get("art/face.png").headers = { "content-length": String(32 * 1024 * 1024 + 1) };
  await rejects(/size limit/);

  reset();
  state.view.foreign = [
    externalOrigin + assetUrl("foreign.png"),
    externalOrigin.replace("http:", "") + assetUrl("protocol-relative.png"),
    assetUrl("other-game.png", "unrelated"),
    origin + assetUrl("art/face.png"),
  ];
  assert.equal((await checkPublicPreviewAssets(origin)).checked, 3);
  assert.equal(requests.some(request => /foreign|protocol-relative|unrelated/.test(request.path)), false, "foreign namespaces and origins are never fetched");
  assert.equal(externalRequests, 0, "redirects and external references never cause a request to another host");
  checks++;

  reset();
  state.view.printings = Array.from({ length: 40 }, (_, index) => ({ id: `p_kindling_${index}`,
    card_id: "kindling", set_id: "core", art_data: assetUrl(`art/card-${index}.png`) }));
  for (let index = 0; index < 40; index++) state.assets.set(`art/card-${index}.png`, { mime: "image/png", bytes: png });
  const sample = await checkPublicPreviewAssets(origin);
  assert.deepEqual(sample, { slug: "public-game", ref, checked: 32, total: 43 });
  assert.ok(requests.some(request => request.path.endsWith(".ttf")), "sample includes fonts despite many card faces");
  assert.ok(requests.some(request => request.path.endsWith(".svg")), "sample includes symbols despite many card faces");
  checks++;

  reset(); state.view.extra = `${assetUrl("icons/%2e%2e%2foutside.svg")}`;
  await rejects(/unsafe asset path/);
  reset();
  await rejects(/slug is invalid/, { slug: "../private" });
  assert.equal(requests.length, 0, "unsafe explicit project identifiers fail before a request");
  await assert.rejects(checkPublicPreviewAssets(`${origin}/path?secret=hidden`), /origin must have no path or credentials/);
  checks++;
  console.log(`PUBLIC PREVIEW ASSETS GREEN — ${checks} checks cover real emitted URLs, anonymous exact assets, bad bytes, redirects and bounded sampling.`);
} finally {
  await close(server);
  await close(external);
}
